def synth_gguf(path, size=4096):
    """A tiny GGUF v3: two KVs (one large string array), two tensors (one rope_freqs.weight with data)."""
    def s(x):
        b = x.encode()
        return struct.pack("<Q", len(b)) + b
    kv = [s("general.architecture") + struct.pack("<I", 8) + s("llama"),
          s("tokenizer.ggml.tokens") + struct.pack("<IIQ", 9, 8, 600) + b"".join(s(f"tok{i:04d}") for i in range(600))]
    rope = struct.pack("<4f", 1.0, 2.0, 3.0, 4.0)
    ti = [s("rope_freqs.weight") + struct.pack("<I", 1) + struct.pack("<Q", 4) + struct.pack("<IQ", 0, 0),
          s("blk.0.attn_q.weight") + struct.pack("<I", 2) + struct.pack("<QQ", 32, 8) + struct.pack("<IQ", 12, 32)]
    head = b"GGUF" + struct.pack("<IQQ", 3, len(ti), len(kv)) + b"".join(kv) + b"".join(ti)
    head += b"\0" * (-len(head) % 32)
    with open(path, "wb") as f:
        f.write(head + rope + b"\0" * 16 + b"\1" * 200)
    return os.path.getsize(path)


class StubTests(unittest.TestCase):
    def test_roundtrip_header_data_and_size(self):
        with tempfile.TemporaryDirectory() as d:
            src, blobs = os.path.join(d, "a.gguf"), os.path.join(d, "blobs")
            synth_gguf(src)
            dump = gguf_stub.dump(src, blobs)
            self.assertTrue(any("blob" in e for e in dump["kv"]))   # the 600-token array goes to the shared store
            self.assertEqual(list(dump["data"]), ["rope_freqs.weight"])
            dp, out = os.path.join(d, "a.json.gz"), os.path.join(d, "stub.gguf")
            gguf_stub.save(dump, dp)
            gguf_stub.write_stub(gguf_stub.load(dp), out, blobs)
            a, b = Path(src).read_bytes(), Path(out).read_bytes()
            self.assertEqual(len(a), len(b))
            self.assertEqual(a[:dump["data_start"] + 16], b[:dump["data_start"] + 16])   # header + rope_freqs data identical
            self.assertEqual(set(b[dump["data_start"] + 32:]), {0})                      # the weights are zeros

    def test_blobs_are_shared(self):
        with tempfile.TemporaryDirectory() as d:
            blobs = os.path.join(d, "blobs")
            for n in ("a", "b"):
                synth_gguf(os.path.join(d, n + ".gguf"))
                gguf_stub.dump(os.path.join(d, n + ".gguf"), blobs)
            self.assertEqual(len(os.listdir(blobs)), 1)


class DiffTests(unittest.TestCase):
    def pkg(self, root, slug, text, cfg=None, mj=None):
        p = Path(root) / slug
        (p / "program").mkdir(parents=True, exist_ok=True)
        (p / "program" / "llm.loom").write_text(text)
        (p / "model.json").write_text(json.dumps(mj or {"presets": {"chat": {"execution": {"rows": 4}}}}))
        (p / "llm_config.json").write_text(json.dumps(cfg or {"arch": "qwen3", "heads": 16, "kv_heads": 8, "head_dim": 128}))

    def run_diff(self, head_text, base_text=PROG, **kw):
        with tempfile.TemporaryDirectory() as d:
            self.pkg(d + "/b", "m1", base_text, **kw)
            self.pkg(d + "/h", "m1", head_text, **kw)
            self.pkg(d + "/b", "m2", base_text)
            self.pkg(d + "/h", "m2", base_text)
            return diff_fleet.report(d + "/b", d + "/h")

    def test_identical_ignores_generated_comment_and_selector_numbers(self):
        head = PROG.replace("/tmp/x/cfg.json", "/other/dir/cfg.json").replace("sel3_", "sel9_")
        r = self.run_diff(head)
        self.assertEqual(r["summary"]["touched"], 0)
        self.assertEqual(sorted(r["untouched"]), ["m1", "m2"])

    def test_blocks_split_by_symbol(self):
        b = diff_fleet.blocks(PROG)
        kinds = sorted((k[0], k[1]) for k in b)
        self.assertIn(("kernel", "g_gemm_q4_k_store"), kinds)
        self.assertIn(("kernel", "g_gemm_q4_k_store_rdna4"), kinds)
        self.assertIn(("func", "g_helper"), kinds)
        self.assertIn(("program", "llm_advance"), kinds)
        self.assertIn(("template", "g_gemm_q4_k_store"), kinds)
        self.assertEqual(sum(1 for k in kinds if k[0] == "decl"), 3)

    def test_gfx12_kernel_change_touches_only_gfx12_prefill(self):
        r = self.run_diff(PROG.replace("// body B", "// body B2"))
        self.assertEqual(r["summary"]["touched"], 1)
        m = r["models"]["m1"]
        self.assertEqual(m["gpus"], ["gfx12"])
        self.assertEqual(m["rows"], ["prefill_1k", "prefill_2k", "prefill_8k", "prefill_16k", "prefill_32k"])
        self.assertEqual([x["symbol"] for x in m["blocks"]], ["g_gemm_q4_k_store_rdna4"])
        self.assertNotIn("m2", r["models"])

    def test_gfx11_and_shared_kernels(self):
        r = self.run_diff(PROG.replace("// body A", "// body A2"))
        self.assertEqual(r["models"]["m1"]["gpus"], ["gfx11"])
        r = self.run_diff(PROG.replace("// matvec", "// matvec2"))
        self.assertEqual(r["models"]["m1"]["gpus"], ["gfx11", "gfx12"])
        self.assertEqual(r["models"]["m1"]["rows"], ["decode", "decode_2k", "decode_32k", "streams4"])

    def single_target(self):
        """PROG as a single-target (gfx11 only) build: no tags, no templates, no declarations, no twin, plain launches."""
        t = PROG.replace(" target(@rdna3) export", " export").replace("target.decl @device\namdgpu.target<gfx11-generic> @rdna3\n"
                         "amdgpu.target<gfx12-generic> @rdna4\n\n", "")
        t = t.replace("template.decl @sel3_g_gemm_q4_k_store(%rows: index)\ntemplate.def<@sel3_g_gemm_q4_k_store> target(@rdna3) {\n"
                      "  kernel.launch @g_gemm_q4_k_store[1](%rows)\n}\n\n", "")
        t = t.replace("command.def target(@device)", "command.def").replace(
            "template.apply<@sel3_g_gemm_q4_k_store>(%t)", "kernel.launch @g_gemm_q4_k_store[%t]()")
        t = t.replace('kernel.def target(@rdna4) export("g_gemm_q4_k_store_rdna4") @g_gemm_q4_k_store_rdna4(%rows: index) {\n  // body B\n}\n\n', "")
        self.assertNotIn("rdna4", t.replace("@rdna4", ""))
        return t

    def test_target_tag_alone_is_not_a_change(self):
        base = PROG.replace('kernel.def target(@rdna3) export("g_gemm_q4_k_store")', 'kernel.def export("g_gemm_q4_k_store")')
        self.assertEqual(self.run_diff(PROG, base_text=base)["summary"]["touched"], 0)

    def test_dual_target_machinery_is_not_a_gfx11_change(self):
        """Tag, template.decl/def, target.decl and launches rewritten as template.apply of the same kernel normalize away; the gfx12 twin
        that arrives with them is a gfx12 change only (finding 1 of the replays: a device/rdna4 row must not read as gfx11)."""
        r = self.run_diff(PROG, base_text=self.single_target())
        m = r["models"]["m1"]
        self.assertEqual(m["gpus"], ["gfx12"])
        self.assertEqual([(x["symbol"], x["target"]) for x in m["blocks"]], [("g_gemm_q4_k_store_rdna4", "gfx12")])
        self.assertNotIn("m2", r["models"])

    def test_comments_between_blocks_do_not_make_a_change(self):
        """A column-0 comment moving to the next block when a block is inserted between them is not a program change."""
        head = PROG.replace("func.def inline @g_helper", "// Helper: identity.\nfunc.def inline @g_helper")
        self.assertEqual(self.run_diff(head)["summary"]["touched"], 0)

    def test_a_real_launch_change_is_still_a_change(self):
        r = self.run_diff(PROG.replace("kernel.launch @g_gemm_q4_k_store[1](%rows)", "kernel.launch @g_gemm_q4_k_store[2](%rows)"),
                          base_text=PROG)
        self.assertEqual(r["models"]["m1"]["gpus"], ["gfx11"])
        # the program launches a different kernel than the base: a (shared) command-program change
        t = self.single_target()
        r = self.run_diff(PROG, base_text=t.replace("@g_gemm_q4_k_store[%t]()", "@g_mv_q4_k_k1024_q8_r1[%t]()"))
        self.assertIn(("llm_advance", "both"), [(x["symbol"], x["target"]) for x in r["models"]["m1"]["blocks"]])

    def test_unmapped_block_moves_all_rows_and_drafting_is_drafted_only(self):
        r = self.run_diff(PROG.replace("func.return %x", "func.return %x /*y*/"))
        self.assertEqual(r["models"]["m1"]["rows"], diff_fleet.load_rules()["groups"]["all"])
        rules = diff_fleet.load_rules()
        self.assertEqual(diff_fleet.rows_for(rules, "kernel", "g_dfl_attention", True)[0], rules["groups"]["drafted_decode"])
        self.assertEqual(diff_fleet.rows_for(rules, "kernel", "g_dfl_attention", False)[2], "unmapped")

    def test_model_json_change_ignores_origins(self):
        mj = {"presets": {"chat": {"execution": {"rows": 4}}}, "origins": {"checkpoint": {"revision": "a"}}}
        with tempfile.TemporaryDirectory() as d:
            self.pkg(d + "/b", "m", PROG, mj=mj)
            mj2 = json.loads(json.dumps(mj))
            mj2["origins"]["checkpoint"]["revision"] = "b"
            self.pkg(d + "/h", "m", PROG, mj=mj2)
            self.assertEqual(diff_fleet.report(d + "/b", d + "/h")["summary"]["touched"], 0)
            mj2["presets"]["chat"]["execution"]["rows"] = 8
            self.pkg(d + "/h", "m", PROG, mj=mj2)
            r = diff_fleet.report(d + "/b", d + "/h")
            self.assertEqual(r["models"]["m"]["model_json"], ["/presets/chat/execution/rows: 4 -> 8"])

    def test_model_json_lists_are_compared_elementwise(self):
        self.assertEqual(diff_fleet.json_diff({"f": [{"path": "a", "origin": "x"}]}, {"f": [{"path": "a", "origin": "y"}]}), [])
        self.assertEqual(diff_fleet.json_diff({"f": [{"path": "a"}]}, {"f": [{"path": "b"}]}), ['/f[0]/path: "a" -> "b"'])

    def test_a_model_the_base_kit_cannot_build_is_new_not_an_error(self):
        # build_fleet.py --ref skips a model whose source path (safetensors) the ref's kit does not have; the diff calls it new
        with tempfile.TemporaryDirectory() as t:
            base, head = Path(t) / "base", Path(t) / "head"
            self.pkg(base, "old", PROG); self.pkg(head, "old", PROG)
            self.pkg(head, "newst", PROG, cfg={"arch": "qwen35", "heads": 24, "kv_heads": 4, "head_dim": 256})
            (base / "summary.json").write_text(json.dumps({"failures": {}, "skipped": {"newst": "skipped"}}))
            rep = diff_fleet.report(str(base), str(head))
            self.assertEqual(rep["untouched"], ["old"])
            self.assertTrue(rep["models"]["newst"]["new_model"])
            self.assertEqual(rep["models"]["newst"]["stratum"]["arch"], "qwen35")
            self.assertEqual(diff_fleet.check_complete(str(base), ["old", "newst"]), [])   # skipped is not "incomplete"
            self.assertIn("new model", diff_fleet.markdown(rep))
            # without the skip record a missing model is still an error
            (base / "summary.json").write_text(json.dumps({"failures": {}}))
            self.assertEqual(diff_fleet.report(str(base), str(head))["models"]["newst"], {"error": "present in only one build"})

    def test_stratum(self):
        st = diff_fleet.strata({"arch": "qwen35moe", "heads": 16, "kv_heads": 2, "head_dim": 256, "drafter": {"kind": "dflash"}, "moe": 1},
                               "kernel.def @g_mv_q4_k_k1024_q8_r1(\nkernel.def @g_gemm_q6_k_store(\n")
        self.assertEqual((st["kv_bucket"], st["draft"], st["topology"], st["formats"]), ("kv<=2", "dflash", "moe", ["q4_k", "q6_k"]))


