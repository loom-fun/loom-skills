def sha_of(label):
    return hashlib.sha1(label.encode()).hexdigest()


def write_tree(root, files):
    for name, content in files.items():
        path = root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(content.encode() if isinstance(content, str) else content)
    return {name: promotion.digest(root / name) for name in files}


def staging_text(slug, extra=None):
    files = {
        "README.md": 'pipx install "hrx-loom[hf]==0.3.0"\n\n```sh\n'
                     f"loom-fetch huggingface:loom-fun-staging/{slug}:default --output=m\nloom-serve --model=m\n```\n",
        "REPORT.md": "Report.\n",
        "info.json": '{\n  "repo": "loom-fun-staging/' + slug + '"\n}\n',
        "llm_config.json": json.dumps({"sdk": {"hrx_loom": "0.3.0"}}),
        "model.json": json.dumps({"presets": {"default": {}}, "services": {"llm": {"kind": "llm"}}}),
        "model.json.lock": "{}",
        "program/llm.loom": "// Generated by kit from cfg\nfunc main\n",
        ".gitattributes": "*.loom text\n",
    }
    files.update(extra or {})
    return files


def production_text(slug, pin="0.2.0"):
    return {"README.md": 'pipx install "hrx-loom[hf]==0.2.0"\n', "info.json": '{"repo": "loom-fun/' + slug + '"}',
            "llm_config.json": json.dumps({"sdk": {"hrx_loom": pin}}), "model.json": "{}", "model.json.lock": "{}",
            "program/llm.loom": "old\n", ".gitattributes": "*.bin filter=lfs\n"}


class FakeHub:
    """Repos with linear commit histories, tags and file maps; snapshot() is served from local directories."""

    def __init__(self, tmp):
        self.tmp, self.repos, self.dirs, self.writes, self.tags_created = tmp, {}, {}, [], []
        self.crash_after_commit, self.before_commit = False, None

    def add(self, repo, files, label):
        commit = sha_of(f"{repo}:{label}:{len(self.dirs)}")
        root = self.tmp / "hub" / commit
        hashes = write_tree(root, files)
        self.repos.setdefault(repo, {"commits": [], "tags": {}})
        self.repos[repo]["commits"].insert(0, SimpleNamespace(commit_id=commit, title=label, message=""))
        self.dirs[commit] = (root, hashes)
        return commit

    def head(self, repo):
        return self.repos[repo]["commits"][0].commit_id

    def resolve(self, repo, revision):
        if revision in (None, "main"):
            return self.head(repo)
        if revision in self.repos[repo]["tags"]:
            return self.repos[repo]["tags"][revision]
        assert any(c.commit_id == revision for c in self.repos[repo]["commits"]), (repo, revision)
        return revision

    # the HfApi surface the scripts use
    def model_info(self, repo, revision=None, token=None, files_metadata=False):
        sha = self.resolve(repo, revision)
        return SimpleNamespace(id=repo, sha=sha, siblings=[SimpleNamespace(rfilename=n) for n in self.dirs[sha][1]])

    def list_repo_refs(self, repo, repo_type="model", token=None):
        return SimpleNamespace(tags=[SimpleNamespace(name=n) for n in self.repos[repo]["tags"]])

    def list_repo_commits(self, repo, revision=None, token=None):
        commits = self.repos[repo]["commits"]
        start = next(i for i, c in enumerate(commits) if c.commit_id == self.resolve(repo, revision))
        return commits[start:]

    def list_models(self, author=None, limit=None, token=None):
        return iter([SimpleNamespace(id=r) for r in self.repos if r.startswith(author + "/")])

    def create_tag(self, repo, tag, revision, tag_message=None):
        assert tag not in self.repos[repo]["tags"]
        self.repos[repo]["tags"][tag] = revision
        self.tags_created.append(repo)

    def create_commit(self, repo, revision, parent_commit, operations, commit_message, commit_description, **_):
        assert revision == "main"
        if self.before_commit:
            hook, self.before_commit = self.before_commit, None
            hook()
        if self.head(repo) != parent_commit:
            raise RuntimeError("412 parent commit mismatch")
        root, hashes = self.dirs[parent_commit]
        files = {n: (root / n).read_bytes() for n in hashes}
        for op in operations:
            if getattr(op, "delete", False):
                files.pop(op.path_in_repo)
            else:
                files[op.path_in_repo] = op.data
        commit = self.add(repo, files, commit_message)
        self.repos[repo]["commits"][0].message = commit_description
        self.writes.append(repo)
        if self.crash_after_commit:
            self.crash_after_commit = False
            raise ConnectionError("response lost after the Hub accepted the commit")
        return SimpleNamespace(oid=commit)

    def snapshot(self, api, repo, revision):
        return self.dirs[self.resolve(repo, revision)]


def card_check_module(directory, problems=None):
    directory.mkdir(parents=True, exist_ok=True)
    (directory / "card_files.py").write_text(
        "def check_package(directory):\n"
        f"    return {problems or []!r} if (directory / 'REPORT.md').exists() else ['REPORT.md missing']\n")
    return directory


class Release:
    """A small release: two promoted text packages and one held repo that still gets its outgoing tag."""

    def __init__(self, tmp):
        self.tmp, self.hub = tmp, FakeHub(tmp)
        self.rows = {}
        for slug in (SLUG, OTHER):
            target = self.hub.add(f"loom-fun/{slug}", production_text(slug), "0.2.0 card")
            staged = self.hub.add(f"loom-fun-staging/{slug}", staging_text(slug), "0.3.0 card")
            self.rows[slug] = {"staging_revision": staged, "target_revision": target, "device_keys": ["strix-halo"]}
        self.held_head = self.hub.add(f"loom-fun/{HELD}", production_text(HELD), "0.2.0 card")
        self.eligible, self.held, self.bundle = tmp / "eligible.json", tmp / "held.json", tmp / "release"
        self.write_inputs()
        self.held.write_text(json.dumps({HELD: {"reason": "owner decision", "tag_revision": self.held_head}}))
        self.card = card_check_module(tmp / "card")

    def write_inputs(self):
        self.eligible.write_text(json.dumps(self.rows))
        shutil.rmtree(self.bundle, ignore_errors=True)

    @contextlib.contextmanager
    def patched(self):
        with patch.object(promotion, "snapshot", self.hub.snapshot), patch.object(promotion, "CARD_SCRIPTS", self.card), \
                patch.object(promotion, "download", lambda repo, name, rev: self.hub.dirs[rev][0] / name), \
                patch.dict(sys.modules, {"huggingface_hub": HUB_MODULE}), \
                patch.dict("os.environ", {"PROMOTE_CONFIRM": "loom-fun"}), contextlib.redirect_stdout(io.StringIO()):
            yield

    def prepare(self, **kwargs):
        with self.patched():
            return promotion.prepare(self.hub, self.eligible, self.held, self.bundle, META, **kwargs)[0]

    def replay(self, sha, execute=True, receipt=None):
        with self.patched():
            return promotion.replay(self.hub, self.bundle, sha, execute, receipt or self.tmp / "receipt.jsonl")

    def tag(self, sha, dry=False):
        out = io.StringIO()
        with contextlib.redirect_stdout(out):
            code = tag_org.main(["--bundle", str(self.bundle), "--manifest-sha256", sha] + (["--dry-run"] if dry else []),
                                api=self.hub)
        return code, out.getvalue()

    def row(self, sha, slug):
        return dict(promotion.inspect_bundle(self.bundle, sha)[1])[slug]


class ReleaseWriterTests(unittest.TestCase):
    def setUp(self):
        self.tmpdir = TemporaryDirectory()
        self.tmp = Path(self.tmpdir.name)
        self.release = Release(self.tmp)

    def tearDown(self):
        self.tmpdir.cleanup()

    def test_composition_rewrites_org_and_keeps_bytes(self):
        sha = self.release.prepare()
        document, rows = promotion.inspect_bundle(self.release.bundle, sha)
        out = self.release.bundle / "packages" / SLUG
        source = self.release.hub.dirs[self.release.rows[SLUG]["staging_revision"]][0]
        self.assertEqual((out / "README.md").read_bytes(),
                         (source / "README.md").read_bytes().replace(b"loom-fun-staging/", b"loom-fun/"))
        self.assertEqual(json.loads((out / "info.json").read_text())["repo"], f"loom-fun/{SLUG}")
        row = dict(rows)[SLUG]
        self.assertNotIn("device_keys", row)  # evidence fields are not release scope
        self.assertEqual(row["output"][".gitattributes"], row["target"][".gitattributes"])
        self.assertNotIn(".gitattributes", row["operations"])
        self.assertEqual(sorted(document["tags"]), sorted([SLUG, OTHER, HELD]))
        self.assertEqual(document["tags"][HELD]["parent"], self.release.held_head)
        self.assertEqual({t["action"] for t in document["tags"].values()}, {"create"})
        runbook = (self.release.bundle / "RELEASE.md").read_text()
        self.assertLess(runbook.index("tag_org.py --bundle DIR --manifest-sha256 SHA`."), runbook.index("Merge the integration"))
        self.assertLess(runbook.index("Merge the integration"), runbook.index("--execute"))
        self.assertIn("pull request", runbook.split("\n4. ", 1)[1].split("\n", 1)[0])
        (out / "REPORT.md").write_text("tampered")
        with self.assertRaisesRegex(ValueError, "incorrect bundle file"):
            promotion.inspect_bundle(self.release.bundle, sha)

