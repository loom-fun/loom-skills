#!/usr/bin/env python3
"""Programs-only build of the whole fleet at a git ref: CPU only, no weights, no HF cache, no GPU.

usage: build_fleet.py --ref REF --out DIR [--jobs N] [--slugs A,B,...] [--rdna4 0|1] [--keep-work] [--real DIR] [--with-gen]
       build_fleet.py --tree PATH --out DIR ...        (a checkout of the skills instead of a ref: the working tree)

For every model of fleet/manifest.json (the inputs of the CURRENT checkout of this tool, not of REF) a work dir gets header-only
GGUF stubs (gguf_stub.py), the kit of REF (the plain starter, or the reference example the package was generated with:
reference/apply_example.sh), inspect_gguf.py on the stub overlaid with the model's llm_config.json, and build.py with the
manifest's execution values and an explicit --memory-gib (never the build machine's RAM). Result, per model:
DIR/<slug>/{program/*.loom, *.loom (weight policies), model.json, llm_config.json, build.log} and DIR/summary.json
(timings, failures). The comment line `// Generated by X from <path>` is rewritten to `from cfg.json` so builds in different
directories compare equal. Default target set: both GPUs (LOOM_RDNA4=1); --rdna4 0 builds the single-target programs.
"""
import argparse
import concurrent.futures as cf
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import gguf_stub  # noqa: E402
import preflight  # noqa: E402

MEMORY_GIB = "4096"   # never the build machine's RAM: with context and pool given, the budget only has to not clamp them
GENERATED = re.compile(r"^(// Generated by \S+ from ).*?([^/ ]+)\.$", re.M)
SKIP = ("gen", "parameter", "tokenizer.json")   # --with-gen keeps gen/ (regen.py package publishes it)
SKIPPED = "skipped: the kit of this ref has no inspector for the model's source (new at the head)"


def sh(cmd, cwd, env=None):
    p = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True, env=env)
    return p.returncode, p.stdout + p.stderr


def normalize(text):
    return GENERATED.sub(lambda m: m.group(1) + "cfg.json.", text)


def unpath(o, prefix):
    """The build records the GGUF paths it was given (draft.gguf, vision.mmproj): keep the file name, not the work dir."""
    if isinstance(o, str):
        return o[len(prefix):] if o.startswith(prefix) else o
    if isinstance(o, dict):
        return {k: unpath(v, prefix) for k, v in o.items()}
    if isinstance(o, list):
        return [unpath(v, prefix) for v in o]
    return o


def kit_dir(skills, example, work):
    kit = os.path.join(work, "kit")
    if example:
        rc, out = sh(["bash", os.path.join(skills, "reference", "apply_example.sh"), example, kit], work)
        if rc:
            raise RuntimeError("apply_example: " + out[-400:])
    else:
        shutil.copytree(os.path.join(skills, "starter"), kit)
    return kit


def build_args(m, cfg_extra=(), slug=None):
    b = m["build"]
    args = (["--slug", slug] if slug else []) + ["--tokenizer", "tokenizer_min.json", "--model-id", m["model_id"], "--memory-gib", MEMORY_GIB]
    for flag, key in (("--context", "context"), ("--pool", "pool"), ("--prefill", "prefill"), ("--rows", "rows"),
                      ("--max-tokens", "max_tokens"), ("--draft-depth", "draft_depth")):
        if b.get(key) is not None:
            args += [flag, str(b[key])]
    return args + list(cfg_extra)


def real_inputs(slug, m, work, real):
    """--real DIR: the proof build. The GGUFs are the files of the HF cache at the pinned revisions (symlinks) and the
    tokenizer is DIR/<slug>/tokenizer.json: the programs must come out byte-identical to the header-stub build."""
    hf = os.path.expanduser(os.environ.get("HF_HUB_CACHE", "~/.cache/huggingface/hub"))
    for name, f in m["files"].items():
        p = f"{hf}/models--{f['repo'].replace('/', '--')}/snapshots/{f['revision']}/{f['path']}"
        if not os.path.exists(p):
            raise FileNotFoundError(f"not in the HF cache at the pinned revision: {f['repo']}@{f['revision'][:8]}/{f['path']}")
        os.symlink(p, os.path.join(work, name))
    shutil.copy(os.path.join(real, slug, "tokenizer.json"), os.path.join(work, "tokenizer_min.json"))


def build_one(slug, m, skills, out, rdna4, keep, real=None, with_gen=False):
    t0 = time.time()
    work = os.path.join(out, "_work", slug)
    shutil.rmtree(work, ignore_errors=True)
    os.makedirs(work)
    log = []
    try:
        st = {n: f for n, f in m["files"].items() if f.get("kind") == "safetensors"}   # an HF safetensors checkpoint: header dump, no stub file
        if real and not st:
            real_inputs(slug, m, work, real)
        else:
            for name, f in m["files"].items():
                if name not in st:
                    gguf_stub.write_stub(gguf_stub.load(os.path.join(HERE, f["dump"])), os.path.join(work, name))
            shutil.copy(os.path.join(HERE, slug, "tokenizer_min.json"), work)
        kit = kit_dir(skills, m.get("kit"), work)
        pcfg = json.load(open(os.path.join(HERE, slug, "llm_config.json")))
        if st and not os.path.exists(os.path.join(kit, "inspect_safetensors.py")):
            # a model whose source path (safetensors) the ref's kit does not have yet: it did not exist there (a new model of a PR
            # that adds the path), not a failure; the diff reports it as a new model
            shutil.rmtree(os.path.join(out, slug), ignore_errors=True)
            return slug, SKIPPED, time.time() - t0
        if st:
            (sname, sf), = st.items()
            ck = os.path.join(work, sname)   # the package links it as parameter/<name>; never read when the build has no weights (cfg source.bytes)
            rc, o = sh([sys.executable, os.path.join(kit, "inspect_safetensors.py"), os.path.join(HERE, sf["dump"]), "fresh.json", "--checkpoint", ck], work)
        else:
            rc, o = sh([sys.executable, os.path.join(kit, "inspect_gguf.py"), os.path.basename(pcfg["gguf"]), "fresh.json"], work)
        log.append(o)
        if rc:
            raise RuntimeError("inspect: " + o.strip().splitlines()[-1][-300:])
        cfg = json.load(open(os.path.join(work, "fresh.json")))
        cfg.update(pcfg)
        json.dump(cfg, open(os.path.join(work, "cfg.json"), "w"), indent=1)
        env = dict(os.environ, LOOM_RDNA4=str(rdna4))
        env.pop("LLM_CONFIG", None)
        kb = os.path.join(skills, "..", "loom-kb")   # the choices build.py resolves (a ref without the registry has none)
        if os.path.isdir(kb) and "LOOM_KB_ROOT" not in env:
            env["LOOM_KB_ROOT"] = os.path.abspath(kb)
        rc, o = sh([sys.executable, os.path.join(kit, "build.py"), "cfg.json", "pkg"] + build_args(m, slug=slug if '"--slug"' in open(os.path.join(kit, "build.py")).read() else None), work, env)
        log.append(o)
        if rc:
            raise RuntimeError("build.py: " + o.strip().splitlines()[-1][-300:])
        dst = os.path.join(out, slug)
        shutil.rmtree(dst, ignore_errors=True)
        os.makedirs(dst)
        pkg = os.path.join(work, "pkg")
        skip = tuple(x for x in SKIP if not (with_gen and x == "gen"))
        for root, dirs, files in os.walk(pkg):
            rel = os.path.relpath(root, pkg)
            dirs[:] = [d for d in dirs if rel != "." or d not in skip]
            for fn in files:
                if rel == "." and fn in skip:
                    continue
                s, d = os.path.join(root, fn), os.path.normpath(os.path.join(dst, rel, fn))
                os.makedirs(os.path.dirname(d), exist_ok=True)
                if fn.endswith(".loom"):
                    open(d, "w", encoding="utf-8", newline="\n").write(normalize(open(s, encoding="utf-8").read()))
                else:
                    shutil.copy(s, d)
        # the build outputs the stamp of the kit's commit: not an input of any program
        p = os.path.join(dst, "llm_config.json")
        c = json.load(open(p))
        c.pop("generator", None)
        json.dump(unpath(c, work + os.sep), open(p, "w"), indent=1)
        open(os.path.join(dst, "build.log"), "w").write("\n".join(log))
        return slug, None, time.time() - t0
    except Exception as e:   # noqa: BLE001
        os.makedirs(os.path.join(out, slug), exist_ok=True)
        open(os.path.join(out, slug, "build.log"), "w").write("\n".join(log) + f"\nFAILED: {e}\n")
        return slug, str(e), time.time() - t0
    finally:
        if not keep:
            shutil.rmtree(work, ignore_errors=True)


def has_output(d):
    """A built model dir holds a model.json and at least one .loom program."""
    if not os.path.isfile(os.path.join(d, "model.json")):
        return False
    return any(f.endswith(".loom") for _, _, fs in os.walk(d) for f in fs)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--ref")
    g.add_argument("--tree")
    ap.add_argument("--out", required=True)
    ap.add_argument("--jobs", type=int, default=os.cpu_count() or 4)
    ap.add_argument("--slugs", default="")
    ap.add_argument("--rdna4", default="1", choices=["0", "1"])
    ap.add_argument("--keep-work", action="store_true")
    ap.add_argument("--with-gen", action="store_true", help="also keep the package's gen/ (generated helper kernels); default: programs only")
    ap.add_argument("--real", help="proof build: GGUFs from the HF cache and DIR/<slug>/tokenizer.json (full tokenizers) instead of stubs")
    a = ap.parse_args()
    preflight.require()
    manifest = json.load(open(os.path.join(HERE, "manifest.json")))["models"]
    slugs = [s for s in a.slugs.split(",") if s] or sorted(manifest)
    unknown = [s for s in slugs if s not in manifest]
    if unknown:
        sys.exit(f"not in fleet/manifest.json: {', '.join(unknown)}")
    out = os.path.abspath(a.out)
    os.makedirs(out, exist_ok=True)
    t0 = time.time()
    tmp = None
    if a.ref:
        repo = subprocess.run(["git", "rev-parse", "--show-toplevel"], cwd=HERE, capture_output=True, text=True, check=True).stdout.strip()
        tmp = tempfile.mkdtemp(prefix="fleet-ref-", dir=out)
        sha = subprocess.run(["git", "rev-parse", a.ref], cwd=repo, capture_output=True, text=True, check=True).stdout.strip()
        subprocess.run(["git", "worktree", "add", "--detach", "-f", os.path.join(tmp, "tree"), sha], cwd=repo, check=True, capture_output=True)
        tree, ref = os.path.join(tmp, "tree"), sha
    else:
        tree, ref = os.path.abspath(a.tree), "tree:" + os.path.abspath(a.tree)
    skills = os.path.join(tree, "skills", "loom-port-llm")
    res, fails, skipped = {}, {}, {}
    try:
        with cf.ProcessPoolExecutor(a.jobs) as ex:
            futs = [ex.submit(build_one, s, manifest[s], skills, out, a.rdna4, a.keep_work, a.real, a.with_gen) for s in slugs]
            for f in cf.as_completed(futs):
                s, err, dt = f.result()
                res[s] = round(dt, 1)
                if err == SKIPPED:
                    skipped[s] = err
                    print(f"skip {s}: {err}", flush=True)
                    continue
                if err:
                    fails[s] = err
                print(f"{'FAIL' if err else 'ok  '} {s} {dt:.0f}s" + (f"  {err[:200]}" if err else ""), flush=True)
    finally:
        if tmp:
            subprocess.run(["git", "worktree", "remove", "--force", os.path.join(tmp, "tree")], cwd=repo, capture_output=True)
            shutil.rmtree(tmp, ignore_errors=True)
        shutil.rmtree(os.path.join(out, "_work"), ignore_errors=True) if not a.keep_work else None
    wall = time.time() - t0
    json.dump({"ref": ref, "rdna4": a.rdna4, "jobs": a.jobs, "wall_s": round(wall, 1), "cpu_s": round(sum(res.values()), 1),
               "models": res, "failures": fails, "skipped": skipped}, open(os.path.join(out, "summary.json"), "w"), indent=1)
    # a build that reported success must have left programs and a model.json (a failed one leaves only build.log)
    for s in slugs:
        if s not in fails and s not in skipped and not has_output(os.path.join(out, s)):
            fails[s] = "no program/*.loom or model.json in the build output"
    print(f"built {len(slugs) - len(fails) - len(skipped)}/{len(slugs)} models in {wall:.0f}s wall ({sum(res.values()):.0f}s of builds)" + (f"; {len(skipped)} new at the head: {', '.join(sorted(skipped))}" if skipped else ""))
    if fails:
        print(f"FAILED {len(fails)} model(s): {', '.join(sorted(fails))}", file=sys.stderr)
    sys.exit(1 if fails else 0)


if __name__ == "__main__":
    main()
