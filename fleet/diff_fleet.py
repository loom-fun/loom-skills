#!/usr/bin/env python3
"""Impact report of two fleet builds (build_fleet.py output dirs, or directories of published packages: <slug>/program/*.loom,
model.json, llm_config.json).

usage: diff_fleet.py BASE_DIR HEAD_DIR [--json OUT.json] [--md OUT.md] [--models A,B]

Per model: changed program files, changed blocks (kernel.def / func.def / command.program.def / template providers / rodata ...)
split by symbol, the GPU target each changed block runs on (gfx11 = plain K or target(@rdna3); gfx12 = K_rdna4 or target(@rdna4);
both = shared blocks), the card rows each block can move (rows_map.json), model.json changes, and the model's stratum signature
(arch, head_dim, G = heads / kv_heads, KV bucket, draft kind, weight formats, dense/moe, vision). Comment lines
`// Generated by ... from <path>` and the numbering of template selectors (@selN_) are ignored. Exit 0 always; an empty report
means the two builds have identical programs and model.json.
"""
import argparse
import hashlib
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
START = re.compile(r"^(kernel\.def|kernel\.decl|func\.def|func\.decl|command\.program\.def|command\.def|command\.decl|template\.def|"
                   r"template\.decl|global\.rodata\.def|config\.decl|config\.def|target\.decl|amdgpu\.target|type\.decl)\b")
KINDS = {"kernel.def": "kernel", "kernel.decl": "kernel", "func.def": "func", "func.decl": "func", "command.program.def": "program",
         "command.def": "program", "command.decl": "program", "template.def": "template", "template.decl": "template",
         "global.rodata.def": "rodata", "config.decl": "config", "config.def": "config", "target.decl": "decl",
         "amdgpu.target": "decl", "type.decl": "decl"}
FAMILY = re.compile(r"_(k|t|h|d|m|n|r)[0-9]+")
SEL = re.compile(r"@sel\d+_")
GENERATED = re.compile(r"^// Generated by .*$", re.M)
FORMATS = ("q4_0", "q4_k", "q5_0", "q5_k", "q6_k", "q8_0", "mxfp4", "bf16", "f16", "f32")
IGNORED_JSON = ("origins", "origin")   # model.json: where the files came from, not what the programs do


def norm(text):
    return SEL.sub("@sel_", GENERATED.sub("", text)).rstrip() + "\n"


def blocks(text):
    """{(kind, symbol, template target or "", nth): (header target, normalized text)} of one program file."""
    lines = text.split("\n")
    starts = [i for i, l in enumerate(lines) if START.match(l)]
    out, seen = {}, {}
    for n, s in enumerate(starts):
        a = s
        while a > 0 and lines[a - 1].startswith("//") and (n == 0 or a - 1 > starts[n - 1]):
            a -= 1   # the comment lines right above a block belong to it
        e = starts[n + 1] if n + 1 < len(starts) else len(lines)
        while e - 1 > s and lines[e - 1].startswith("//") and n + 1 < len(starts):
            e -= 1
        head = lines[s]
        word = START.match(head).group(1)
        kind = KINDS[word]
        tgt = re.search(r"target\(@(\w+)\)", head)
        tgt = tgt.group(1) if tgt else None
        bare = re.sub(r"target\(@\w+\)", "", head)   # the first @symbol of the rest is the block's own name
        m = re.search(r"template\.def<@([\w.]+)>", bare) or re.search(r"@([\w.]+)", bare)
        sym = re.sub(r"^sel\d+_", "", m.group(1)) if m else hashlib.sha1(head.encode()).hexdigest()[:8]
        key = (kind, sym, (tgt or "") if kind == "template" else "")   # a kernel that gains target(@rdna3) is changed, not removed
        k = seen.get(key, 0)
        seen[key] = k + 1
        out[(kind, sym, key[2], k)] = (tgt, norm("\n".join(lines[a:e])))
    return out


def block_target(kind, sym, tgt):
    """gfx11 / gfx12 / both for a block of a dual-target program."""
    if tgt == "rdna3":
        return "gfx11"
    if tgt == "rdna4" or sym.endswith("_rdna4"):
        return "gfx12"
    return "both"


def family_symbol(sym):
    return re.sub(r"_rdna4$", "", sym)


def load_rules():
    return json.load(open(os.path.join(HERE, "rows_map.json")))


def rows_for(rules, kind, sym, drafted):
    s = family_symbol(sym)
    for r in rules["rules"]:
        if r["kind"] != kind or not re.search(r["match"], s):
            continue
        if r.get("drafted_only") and not drafted:
            continue
        rows = r["rows"]
        rows = rules["groups"][rows] if isinstance(rows, str) else rows
        return list(rows), list(r.get("gates", [])), r["id"]
    rows = rules["unmapped"]
    return list(rules["groups"][rows]), [], "unmapped"


def strata(cfg, programs_text):
    """The stratum signature of a model (what samples must cover): arch, head_dim, G, KV bucket, draft kind, formats, topology."""
    heads, kv = cfg.get("heads") or 0, cfg.get("kv_heads") or 0
    bucket = "kv<=2" if kv <= 2 else ("kv4" if kv < 8 else "kv>=8")
    d = cfg.get("draft") or {}
    kind = d.get("kind") if isinstance(d, dict) and d.get("kind") else ("none" if not cfg.get("drafter") else (cfg["drafter"].get("kind") or "none"))
    fmts = sorted({f for f in FORMATS if re.search(rf"^kernel\.def.*@g_(mv|gemm|head_mv|moe_\w+)_{f}(_|\()", programs_text, re.M)
                   or re.search(rf"@g_(mv|gemm|head_mv)_{f}_", programs_text)})
    moe = bool(cfg.get("moe")) or "@g_moe_route" in programs_text
    return {"arch": cfg.get("arch"), "head_dim": cfg.get("head_dim"), "G": round(heads / kv, 2) if kv else None,
            "kv_heads": kv, "kv_bucket": bucket, "draft": kind, "formats": fmts, "topology": "moe" if moe else "dense",
            "vision": bool(cfg.get("vision")), "hybrid": bool(cfg.get("recurrent_layers"))}


def _read(path, loader=None):
    with open(path, encoding="utf-8") as f:
        return loader(f) if loader else f.read()


def read_dir(d, slug):
    p = os.path.join(d, slug)
    progs = {}
    for root, dirs, files in os.walk(p):
        if os.path.relpath(root, p).split(os.sep)[0] in ("gen", "parameter"):   # generator scratch of a published package
            continue
        for fn in sorted(files):
            if fn.endswith(".loom"):
                progs[os.path.relpath(os.path.join(root, fn), p)] = _read(os.path.join(root, fn))
    mj = _read(os.path.join(p, "model.json"), json.load) if os.path.exists(os.path.join(p, "model.json")) else None
    cfg = _read(os.path.join(p, "llm_config.json"), json.load) if os.path.exists(os.path.join(p, "llm_config.json")) else {}
    return progs, mj, cfg


def json_diff(a, b, path=""):
    out = []
    if isinstance(a, dict) and isinstance(b, dict):
        for k in sorted(set(a) | set(b)):
            if k in IGNORED_JSON:
                continue
            if k not in a:
                out.append(f"{path}/{k}: added")
            elif k not in b:
                out.append(f"{path}/{k}: removed")
            else:
                out += json_diff(a[k], b[k], f"{path}/{k}")
    elif isinstance(a, list) and isinstance(b, list) and len(a) == len(b):
        for i, (x, y) in enumerate(zip(a, b)):
            out += json_diff(x, y, f"{path}[{i}]")
    elif a != b:
        out.append(f"{path}: {json.dumps(a)[:60]} -> {json.dumps(b)[:60]}")
    return out


def diff_model(base, head, slug, rules):
    bp, bm, bc = read_dir(base, slug)
    hp, hm, hc = read_dir(head, slug)
    cfg = hc or bc
    text = "\n".join(hp.values()) or "\n".join(bp.values())
    st = strata(cfg, text)
    drafted = st["draft"] != "none"
    files, changed, rows, gates, targets = [], [], set(), set(), set()
    for f in sorted(set(bp) | set(hp)):
        if f not in bp or f not in hp:
            files.append(f"{f} ({'added' if f not in bp else 'removed'})")
        a = blocks(bp[f]) if f in bp else {}
        b = blocks(hp[f]) if f in hp else {}
        fch = False
        for key in sorted(set(a) | set(b)):
            if (a.get(key) or (0, 0))[1] == (b.get(key) or (1, 1))[1] and key in a and key in b:
                continue
            fch = True
            kind, sym, _, _ = key
            status = "added" if key not in a else ("removed" if key not in b else "changed")
            t = block_target(kind, sym, (b.get(key) or a.get(key))[0])
            r, g, rid = rows_for(rules, kind, sym, drafted)
            changed.append({"file": f, "kind": kind, "symbol": sym, "target": t, "status": status, "rule": rid, "rows": r, "gates": g})
            rows |= set(r)
            gates |= set(g)
            targets.add(t)
        if fch:
            files.append(f)
    mjd = json_diff(bm, hm) if bm and hm else (["model.json: added or removed"] if bool(bm) != bool(hm) else [])
    if not (changed or mjd or files):
        return None
    if mjd:
        targets.add("config")
    order = rules["rows"]
    gpus = sorted(({"gfx11": ["gfx11"], "gfx12": ["gfx12"], "both": ["gfx11", "gfx12"]}.get(t, []) for t in targets), key=len)
    gset = sorted({x for g in gpus for x in g})
    return {"files": sorted(set(f.split(" ")[0] for f in files)), "blocks": changed, "model_json": mjd, "gpus": gset,
            "rows": [r for r in order if r in rows], "gates": sorted(gates), "stratum": st}


def report(base, head, models=None):
    rules = load_rules()
    slugs = sorted(s for s in set(os.listdir(base)) | set(os.listdir(head)) if os.path.isdir(os.path.join(base, s)) or os.path.isdir(os.path.join(head, s)))
    slugs = [s for s in slugs if not s.startswith("_") and (not models or s in models)]
    out = {"base": base, "head": head, "models": {}, "untouched": []}
    for s in slugs:
        if not (os.path.isdir(os.path.join(base, s)) and os.path.isdir(os.path.join(head, s))):
            out["models"][s] = {"error": "present in only one build"}
            continue
        r = diff_model(base, head, s, rules)
        if r:
            out["models"][s] = r
        else:
            out["untouched"].append(s)
    fam = {}
    for s, r in out["models"].items():
        for b in r.get("blocks", []):
            fam.setdefault(f"{b['kind']}:{FAMILY.sub(lambda m: '_' + m.group(1) + 'N', family_symbol(b['symbol']))}", set()).add(s)
    out["by_family"] = {k: sorted(v) for k, v in sorted(fam.items())}
    out["summary"] = {"models": len(slugs), "touched": len(out["models"]), "untouched": len(out["untouched"]),
                      "gpus": sorted({g for r in out["models"].values() for g in r.get("gpus", [])}),
                      "rows": [r for r in rules["rows"] if any(r in m.get("rows", []) for m in out["models"].values())],
                      "strata": sorted({json.dumps({k: v for k, v in m["stratum"].items() if k in ("arch", "head_dim", "kv_bucket", "draft", "topology")}, sort_keys=True)
                                        for m in out["models"].values() if "stratum" in m})}
    return out


def markdown(rep):
    s = rep["summary"]
    L = [f"## Fleet program diff: {s['touched']} of {s['models']} models touched", ""]
    if not s["touched"]:
        return "\n".join(L + ["No program or model.json differs (identical on all models)."]) + "\n"
    L += [f"GPUs: {', '.join(s['gpus']) or '-'}; rows that can move: {', '.join(s['rows']) or '-'}", "",
          "| model | files | blocks (+/-/~) | GPUs | rows | stratum |", "|---|---|---|---|---|---|"]
    for m, r in rep["models"].items():
        if "error" in r:
            L.append(f"| {m} | {r['error']} | | | | |")
            continue
        c = {k: sum(1 for b in r["blocks"] if b["status"] == k) for k in ("added", "removed", "changed")}
        st = r["stratum"]
        L.append(f"| {m} | {', '.join(r['files'])}{' +model.json' if r['model_json'] else ''} | {c['added']}/{c['removed']}/{c['changed']} | "
                 f"{'+'.join(r['gpus']) or '-'} | {', '.join(r['rows']) or '-'} | {st['arch']} hd{st['head_dim']} {st['kv_bucket']} {st['draft']} {st['topology']} |")
    L += ["", "### Changed kernel families (models)", ""]
    for k, v in list(rep["by_family"].items())[:60]:
        L.append(f"- `{k}`: {len(v)} model(s)")
    return "\n".join(L) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("base")
    ap.add_argument("head")
    ap.add_argument("--json")
    ap.add_argument("--md")
    ap.add_argument("--models", default="")
    a = ap.parse_args()
    rep = report(os.path.abspath(a.base), os.path.abspath(a.head), set(x for x in a.models.split(",") if x))
    if a.json:
        json.dump(rep, open(a.json, "w"), indent=1)
    md = markdown(rep)
    if a.md:
        open(a.md, "w").write(md)
    else:
        print(md)


if __name__ == "__main__":
    main()
